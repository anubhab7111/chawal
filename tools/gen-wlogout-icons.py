#!/usr/bin/env python3
"""Draw the wlogout icons for every theme from the Nerd Font glyphs Waybar uses.

For each theme under config-theming/.config/theming/themes/ this writes, into
<theme>/wlogout-icons/:

  lock.svg ...        in an accent colour: the icon on a resting (glass) tile
  lock-focus.svg ...  in the theme's pill text colour: the icon on the tile
                      once it fills with its gradient (focus or hover)

The colours are read from the theme's waybar-colors.css, so after a palette
edit, re-running this keeps the icons in step. wlogout's style.css reaches the
files through ~/.config/theming/current/wlogout-icons.

usage:  tools/gen-wlogout-icons.py [FONT.ttf]
needs:  python-fonttools, and a JetBrainsMono Nerd Font (Mono) file; the
        default is the Arch ttf-jetbrains-mono-nerd path.
"""
import re
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

DEFAULT_FONT = "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Bold.ttf"
THEMES = Path(__file__).resolve().parent.parent / "config-theming/.config/theming/themes"

# wlogout button label -> (Nerd Font code point, palette colour for the resting icon)
ICONS = {
    "lock": (0xF033E, "green"),      # nf-md-lock
    "logout": (0xF0343, "mauve"),    # nf-md-logout
    "shutdown": (0xF0425, "red"),    # nf-md-power
    "suspend": (0xF04B2, "yellow"),  # nf-md-sleep
    "reboot": (0xF0709, "blue"),     # nf-md-restart
}
FOCUS_COLOUR = "pill_fg"  # text colour on the Waybar pill gradients
BOX = 64                  # viewBox size
FIT = 52                  # the glyph's longer side, leaving a margin


def palette(css: Path) -> dict:
    """@define-color NAME #rrggbb; lines of a theme's waybar-colors.css."""
    found = re.findall(r"@define-color\s+(\w+)\s+(#[0-9a-fA-F]{6})\s*;", css.read_text())
    return dict(found)


def svg_for(glyphs, glyph_name: str, fill: str) -> str:
    glyph = glyphs[glyph_name]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    w, h = x1 - x0, y1 - y0
    scale = FIT / max(w, h)
    # font units are y-up, SVG is y-down: scale, flip and centre in the box
    tx = (BOX - w * scale) / 2 - x0 * scale
    ty = (BOX - h * scale) / 2 + y1 * scale
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}")
    glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, tx, ty)))
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{BOX}" height="{BOX}" viewBox="0 0 {BOX} {BOX}">\n'
        f"  <!-- generated by tools/gen-wlogout-icons.py: edit that, not this -->\n"
        f'  <path fill="{fill}" d="{pen.getCommands()}"/>\n'
        f"</svg>\n"
    )


def main() -> None:
    font_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FONT
    font = TTFont(font_path)
    cmap = font.getBestCmap() or {}
    glyphs = font.getGlyphSet()

    for theme in sorted(p for p in THEMES.iterdir() if (p / "waybar-colors.css").is_file()):
        colours = palette(theme / "waybar-colors.css")
        out = theme / "wlogout-icons"
        out.mkdir(exist_ok=True)
        for name, (code_point, accent) in ICONS.items():
            if code_point not in cmap:
                sys.exit(f"{font_path} has no glyph U+{code_point:X} for {name}")
            for needed in (accent, FOCUS_COLOUR):
                if needed not in colours:
                    sys.exit(f"{theme.name}: waybar-colors.css has no @define-color {needed}")
            glyph_name = cmap[code_point]
            (out / f"{name}.svg").write_text(svg_for(glyphs, glyph_name, colours[accent]))
            (out / f"{name}-focus.svg").write_text(svg_for(glyphs, glyph_name, colours[FOCUS_COLOUR]))
        print(f"{theme.name}: {len(ICONS) * 2} icons in {out}")


if __name__ == "__main__":
    main()
